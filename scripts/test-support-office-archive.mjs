import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PgDialect } from 'drizzle-orm/pg-core';
import { officeArchiveFilter, officeRequestScopeFilter } from '../api/_shared/support-office-archive.ts';
import { isOfficeArchived, isOfficeArchiveInput } from '../shared/support-office-archive.ts';
const stamp = '2026-10-11T18:00:00.000Z';
assert.equal(isOfficeArchived({ officeArchive: stamp }), true);
assert.equal(isOfficeArchived({ officeArchive: stamp }, [{ direction: 'inbound', createdAt: '2026-10-11T18:01:00.000Z' }]), false);
assert.equal(isOfficeArchived({ officeArchive: stamp }, [{ direction: 'outbound', createdAt: '2026-10-11T18:01:00.000Z' }]), true);
assert.equal(isOfficeArchived({ officeArchive: 'invalid' }), false);
const input = { publicCode: 'BC-2026-002933', archived: true, expectedUpdatedAt: stamp };
assert.equal(isOfficeArchiveInput(input), true);
assert.equal(isOfficeArchiveInput({ ...input, status: 'resolu' }), false);
assert.equal(isOfficeArchiveInput({ ...input, institutionId: 'other' }), false);
assert.equal(isOfficeArchiveInput({ ...input, archived: 'true' }), false);
assert.equal(isOfficeArchiveInput({ ...input, publicCode: '../other' }), false);
assert.equal(isOfficeArchiveInput({ ...input, expectedUpdatedAt: 'bad' }), false);
const dialect = new PgDialect();
const compiled = dialect.sqlToQuery(officeArchiveFilter('only'));
assert.match(compiled.sql, /request\.archived/);
assert.match(compiled.sql, /request\.restored/);
assert.match(compiled.sql, /msg\.created_at > evt\.created_at/);
assert.match(compiled.sql, /evt\.id desc/);
assert.equal(officeArchiveFilter('include'), undefined);
assert.match(dialect.sqlToQuery(officeArchiveFilter('')).sql, /^not/);
assert.match(dialect.sqlToQuery(officeRequestScopeFilter('', '')).sql, /materiel_lycee/);
assert.equal(officeRequestScopeFilter('equipment', ''), undefined);
assert.equal(officeRequestScopeFilter('digital', ''), undefined);
assert.equal(officeRequestScopeFilter('', 'ordinateur'), undefined);
const route = fs.readFileSync('api/support/agent/archive.ts', 'utf8');
assert.match(route, /requireSupportAgent/);
assert.match(route, /assertSupportRequestAccess/);
assert.match(route, /db\.transaction/);
assert.match(route, /\.for\("update"\)/);
assert.doesNotMatch(route, /resolvedAt:|closedAt:|identityStatus:|supportJobs|supportMessages/);
const sql = `with support_requests(id, category, subcategory) as (values ('a','ent',null), ('b','ent',null), ('c','ent',null), ('d','ent',null), ('e','ordinateur','materiel_lycee')), support_events(id,request_id,event_type,created_at) as (values (1,'a','request.archived',timestamp '2026-10-11 18:00'), (2,'b','request.archived',timestamp '2026-10-11 18:00'), (3,'c','request.archived',timestamp '2026-10-11 18:00'), (4,'c','request.restored',timestamp '2026-10-11 18:01')), support_messages(request_id,direction,created_at) as (values ('b','inbound',timestamp '2026-10-11 18:01'), ('a','outbound',timestamp '2026-10-11 18:01')) select id, (${compiled.sql}) as archived from support_requests order by id;`;
fs.writeFileSync('archive-fixtures.sql', sql);
console.log('Archive policy: identity/status preserved, input/perimeter checks, new inbound and restore tested. SQL fixtures generated.');
